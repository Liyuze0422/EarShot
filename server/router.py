# -*- coding: utf-8 -*-
"""问题分类：决定用哪种回答策略。规则法，0 延迟（<1ms）。

分类准则不是"语言学分类"，而是"这题该用哪套答案策略"：
  experience  答案必须由我的真实材料支撑（我的项目 / 我的做法 / 我的履历 / 我的团队角色）
  design      材料里没有，要现场搭思路，可能结合对方公司
  behavior    冲突 / 失败 / 缺点 这类要讲故事的题
  motivation  动机、离职、规划
  reverse     把提问权交给我
  skip        不是提问（闲聊、设备调试、面试官自述）
  unknown     兜底

为什么这么宽：用 2026-08-31 那场真实一面（50 段面试官发言）做回归测试发现，
面试官的实际提问极其口语化——"那个推荐系统是你自己搭的吗""数据量有多大呢""双塔是吧"——
旧规则只认"你在 / 怎么做的 / 为什么用"这类书面词，真实题命中率只有 2.3%。
新规则把"是不是 / 对吗 / 哪些 / 什么作用 / 怎么来"这一层也算进来，
并且做了一条兜底判断：只要是真提问、又没命中其它策略，就按经历线走
（真实面试 44 条提问里 39 条是项目深挖，经历线对材料最敏感、最不容易编）。
"""
import re

# ── 1) 不是提问：设备调试 / 寒暄 / 面试官自述 / 跑题的设备闲聊 ──────────────
SKIP = [
    r'听得到吗', r'听得到', r'能听到', r'听得清', r'听得见',
    r'声音(大|小|放大|清楚)', r'麦克风', r'摄像头', r'视频(出来|开了?|卡|没)',
    r'咋没有', r'怎么没有(视频|声音|画面)', r'稍等', r'等我一下', r'我先打开',
    r'^我了解了', r'我这边(没什么|没有问题)', r'^(行|好)[，,]\s*我这边', r'你继续',
    r'我为什么这么问', r'我这么问(是)?因为', r'我是本(次|场)的面试官',
    r'你(的)?(手机|电脑|网络)(内存|配置|型号|怎么样|什么牌子)',
    r'^(喂|你好|在吗|在不在|嗯|哦|好的|行)[?？。！!，,]*$',
]
# ── 2) 开放式设计题：假设句 / 从零搭 / 结合对方公司 ────────────────────────
DESIGN = [
    r'如果(让|给|是|要|我们|需要|你)', r'假如', r'假设', r'要是(让|你)',
    r'你会(怎么|如何|选|设计|做|落地)', r'你打算(怎么|如何)',
    r'你(会)?怎么(去)?(设计|搭建|建|构建|打造|做技术选型|落地)',
    r'如何设计', r'怎么设计', r'怎么(去)?(搭建|搭|构建|建设|负责)',
    r'结合(我们|贵|你们)', r'(给|帮)我们(设计|提|想|做)', r'提个方案',
    r'有什么思路', r'你的思路', r'你怎么看', r'从零',
]
# ── 3) 行为面试题：要讲故事 ───────────────────────────────────────────────
BEHAVIOR = [
    r'冲突', r'缺点', r'不足(是|在哪)', r'失败', r'遗憾', r'压力', r'挫折',
    r'最难(的)?(一次|经历|问题|地方)', r'讲(一次|一个|个|讲).{0,8}(经历|事|例子)',
    r'团队协作', r'协作', r'被.{0,4}质疑', r'犯过.{0,4}错', r'怎么处理.{0,6}(关系|分歧)',
    r'沟通过.{0,6}(困难|问题)',
]
# ── 4) 动机意向题 ────────────────────────────────────────────────────────
MOTIVATION = [
    r'为什么(选|来|想|要|会).{0,6}(我们|公司|贵司|这里|一家)', r'职业规划',
    r'未来.{0,6}(打算|规划|计划)', r'(三|3|五|5)年.{0,6}(规划|计划|打算)',
    r'期望.{0,6}(薪资|待遇)', r'为什么离职', r'为什么(要)?(换|离开)',
    r'为什么.{0,6}(刚)?毕业.{0,6}(换|跳)', r'为什么.{0,6}(换|跳|离开).{0,6}(公司|一家)',
]
# ── 5) 反问机会 ──────────────────────────────────────────────────────────
REVERSE = [
    r'你(还)?有什么.{0,6}(想问|要问|问题|提问|想了解|了解)',
    r'有(什么|没有).{0,6}问题.{0,6}(问|了解)', r'反问', r'你想(要)?了解(什么|哪些)',
]
# ── 6) 真提问兜底：有疑问形式就当"在问我" ─────────────────────────────────
QUESTION_FORM = re.compile(
    r'[?？]|吗|嘛|呢|什么|怎么|咋|为什么|为啥|哪|多少|几(个|种|台|层|条)|是不是|有没有|'
    r'介绍|讲讲|说说|举例|聊一聊|做过|用过|了解了?吗')

_SKIP = [re.compile(p) for p in SKIP]
_RULES = [
    ('design', [re.compile(p) for p in DESIGN]),
    ('behavior', [re.compile(p) for p in BEHAVIOR]),
    ('motivation', [re.compile(p) for p in MOTIVATION]),
    ('reverse', [re.compile(p) for p in REVERSE]),
]

LABEL = {
    'design': '开放式设计题',
    'experience': '经历深挖题',
    'behavior': '行为面试题',
    'motivation': '动机意向题',
    'reverse': '反问机会',
    'skip': '非提问(过滤)',
    'gap': '没准备过的名词',
    'unknown': '通用题',
}


def is_skip(q):
    """不是提问 → 不该浪费一次大模型调用。"""
    s = (q or '').strip()
    if len(s) < 2:
        return True
    for p in _SKIP:
        if p.search(s):
            return True
    # 既没问号也没任何疑问词 → 面试官在下结论/自言自语
    return not QUESTION_FORM.search(s)


def classify(q):
    if is_skip(q):
        return 'skip'
    for name, pats in _RULES:
        for p in pats:
            if p.search(q):
                return name
    if QUESTION_FORM.search(q):
        return 'experience'
    return 'unknown'
